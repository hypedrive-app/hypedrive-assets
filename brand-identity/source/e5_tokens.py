"""Kit tokens = the app's E5 tokens. Reads the repo's generated colours and writes BRAND/tokens/colors-app.css
(same variable names as colors.css; brand ramps and the brand book keep colors.css)."""
import re, os, sys
B = os.path.expanduser("~/Downloads/hypedrive-wordmark/BRAND")
TS = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Documents/hypedrive/packages/design-tokens/generated/mobile/colors.ts")
src = open(os.path.join(B, "tokens", "colors.css")).read()
roles = {m[0]: (m[1], m[2]) for m in re.findall(r'"([a-z0-9-]+)": \{ light: "([^"]+)", dark: "([^"]+)" \}', open(TS).read())}
MAP = {
 "bg": "card", "bg-subtle": "well", "canvas": "bed", "surface": "card", "surface-raised": "raised", "surface-sunken": "well",
 "overlay": "raised", "fg": "ink", "fg-muted": "ink-2", "fg-subtle": "ink-3", "border": "line", "border-strong": "line-strong",
 "accent": "accent", "accent-hover": "accent-hover", "accent-pressed": "accent-press", "accent-subtle": "accent-soft",
 "focus": "accent", "link": "accent-text", "indicator": "accent", "data-1": "accent", "tone-cobalt": "accent",
 "success": "success-text", "success-subtle": "success-soft", "success-strong": "success-text", "success-solid": "success",
 "warning": "warning-text", "warning-subtle": "warning-soft", "warning-strong": "warning-text",
 "danger": "danger-text", "danger-subtle": "danger-soft", "danger-strong": "danger-text",
 "danger-solid": "danger-solid", "danger-solid-hover": "danger-solid-hover", "danger-edge": "danger-text",
 "info": "info-text", "info-subtle": "info-soft", "info-strong": "info-text",
 "control": "control", "control-hover": "line-strong", "control-pressed": "line-strong", "control-edge": "line-strong",
 "track": "control", "track-strong": "ink-3", "skeleton": "skeleton", "skeleton-hi": "well",
 "inverse": "ink", "inverse-fg": "card", "focus-ring": "accent-ring",
 "border-input": "control-strong", "border-input-hover": "ink-3",
 "tone-vermilion": "danger", "tone-marigold": "warning", "tone-mint": "success", "tone-ink": "ink-3",
}
missing = sorted({r for r in MAP.values() if r not in roles})
if missing: sys.exit(f"E5 roles missing: {missing}")
def block(sel, i):
    global src
    m = re.search(re.escape(sel) + r" \{([^}]*)\}", src)
    body = m.group(1)
    for k, r in MAP.items():
        body = re.sub(rf"(--hd-{k}): [^;]*;", rf"\1: {roles[r][i]};", body)
    body = re.sub(r"(--hd-brand-ink): [^;]*;", rf"\1: {roles['ink'][0]};", body)
    src = src[:m.start(1)] + body + src[m.end(1):]
block('[data-theme="light"]', 0); block('[data-theme="dark"]', 1)
# :root carries the light roles too, and the UI face
m = re.search(r":root \{([^}]*)\}", src); body = m.group(1)
for k, r in MAP.items(): body = re.sub(rf"(--hd-{k}): [^;]*;", rf"\1: {roles[r][0]};", body)
body = re.sub(r"(--hd-font-ui): [^;]*;", r"\1: 'Allo', ui-sans-serif, system-ui, sans-serif;", body)
body = re.sub(r"(--hd-font-body): [^;]*;", r"\1: 'Allo', ui-sans-serif, system-ui, sans-serif;", body)
src = src[:m.start(1)] + body + src[m.end(1):]
open(os.path.join(B, "tokens", "colors-app.css"), "w").write("/* GENERATED by e5_tokens.py from the app's E5 tokens. Kit only; the brand book uses colors.css. */\n" + src)
print("ok", len(MAP))
